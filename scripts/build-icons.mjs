/**
 * Extracts the Lucide icons the UI uses (from https://icones.js.org/collection/lucide)
 * into src/lib/icons.generated.ts so the bundle ships only what it needs.
 *
 * Run: pnpm icons:ui
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const set = JSON.parse(
  readFileSync(join(root, "node_modules/@iconify-json/lucide/icons.json"), "utf8")
);

const NAMES = [
  "git-merge",
  "git-pull-request",
  "refresh-cw",
  "arrow-up-down",
  "external-link",
  "copy",
  "eye-off",
  "settings",
  "sun",
  "moon",
  "monitor",
  "plus",
  "arrow-left",
  "inbox"
];

const entries = NAMES.map((name) => {
  const icon = set.icons[name] ?? set.icons[set.aliases?.[name]?.parent];
  if (!icon) throw new Error(`Icon "${name}" not found in lucide set`);
  return `  ${JSON.stringify(name)}: ${JSON.stringify(icon.body)}`;
});

const out = `// Generated by scripts/build-icons.mjs — do not edit.
// Source: Lucide via Iconify (https://icones.js.org/collection/lucide), ISC license.

export const ICON_BODIES = {
${entries.join(",\n")}
} as const;

export type IconName = keyof typeof ICON_BODIES;
`;
writeFileSync(join(root, "src/lib/icons.generated.ts"), out);
console.log(`Wrote ${NAMES.length} icons`);
